"""Generate a photon-IMRT beam model from a geometry + beam set.

Adapter between Service 2's modality-neutral types and OpenTPS's
``PhotonPlan`` construction. :func:`build_photon_plan` is the only place
that knows how to assemble an OpenTPS photon plan; the legacy
``photon_ccc`` workflow uses it too.

v1 scope: each beam carries one ``PlanPhotonSegment`` — an open MLC
aperture the size of the jaw opening — and its beamlets are generated by
OpenTPS's ``createBeamletsFromSegments``. The "fluence element" count for
a beam is the number of beamlet pixels that fit inside the jaw opening;
``active_beamlets`` is the number OpenTPS actually created, which can
differ by a row or column because OpenTPS centres beamlets on a
half-pixel grid. Real multi-segment IMRT arrives with the machine model
and leaf sequencer (roadmap R4).

OpenTPS conventions (``_planPhotonBeam.py``, ``_planPhotonSegment.py``):
beams are added with ``appendBeam`` and segments with
``appendBeamSegment`` — the ``beams`` property returns a *copy*, so
appending to it does nothing; angles are ``gantryAngle_degree`` /
``couchAngle_degree``; a segment carries ``mu``, ``x_jaw_mm`` and
``y_jaw_mm`` as ``[min, max]``, and ``Xmlc_mm`` as one row per leaf
pair ``[y_min, y_max, x_left, x_right]``.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from typing import Any, List, Sequence, Tuple

import numpy as np
from loguru import logger

from ..models.beam_model import (
    BeamSetSpec,
    DeliveryParams,
    FluenceElementSet,
    PerBeamElements,
)
from .machine_model import PhotonMachineModel


@dataclass
class PhotonBuildResult:
    """Internal bundle — the FluenceElementSet plus the OpenTPS plan."""

    fluence_elements: FluenceElementSet
    plan: Any  # OpenTPS PhotonPlan (or test double)


def open_field_mlc(
    jaw_x_mm: Tuple[float, float],
    jaw_y_mm: Tuple[float, float],
    leaf_width_mm: float,
) -> np.ndarray:
    """MLC rows for an open field: every leaf pair parked at the X jaws.

    One row per leaf pair across the Y jaw opening, in the
    ``[y_min, y_max, x_left, x_right]`` layout OpenTPS reads.
    """
    y_min, y_max = float(jaw_y_mm[0]), float(jaw_y_mm[1])
    x_min, x_max = float(jaw_x_mm[0]), float(jaw_x_mm[1])
    n_leaves = max(1, math.ceil((y_max - y_min) / float(leaf_width_mm)))
    rows = []
    for k in range(n_leaves):
        y0 = y_min + k * float(leaf_width_mm)
        y1 = min(y0 + float(leaf_width_mm), y_max)
        rows.append([y0, y1, x_min, x_max])
    return np.asarray(rows, dtype=float)


def build_photon_plan(
    beams: Sequence[Tuple[float, float]],
    jaw_x_mm: Tuple[float, float],
    jaw_y_mm: Tuple[float, float],
    leaf_width_mm: float,
    mu_per_beam: float,
    beamlet_spacing_mm: Tuple[float, float] = (5.0, 5.0),
    isocenter_mm: Tuple[float, float, float] = (0.0, 0.0, 0.0),
    name: str = "PhotonPlan",
):
    """Assemble an OpenTPS ``PhotonPlan`` of open fields.

    Parameters
    ----------
    beams
        ``(gantry_deg, couch_deg)`` per beam, in beam order.
    jaw_x_mm, jaw_y_mm
        Jaw positions as ``(min, max)`` at isocenter.
    leaf_width_mm
        MLC leaf width; defines the rows of the open aperture.
    mu_per_beam
        Meterset for the single segment of each beam.
    beamlet_spacing_mm
        Beamlet pixel size in beam's-eye view.
    """
    from opentps.core.data.plan._photonPlan import PhotonPlan
    from opentps.core.data.plan._planPhotonBeam import PlanPhotonBeam
    from opentps.core.data.plan._planPhotonSegment import PlanPhotonSegment

    bx, by = float(beamlet_spacing_mm[0]), float(beamlet_spacing_mm[1])
    mlc = open_field_mlc(jaw_x_mm, jaw_y_mm, leaf_width_mm)
    iso = [float(v) for v in isocenter_mm]

    plan = PhotonPlan(name=name)
    for idx, (gantry, couch) in enumerate(beams):
        beam = PlanPhotonBeam()
        beam.id = idx
        beam.name = f"Beam{idx + 1}"
        beam.gantryAngle_degree = float(gantry)
        beam.couchAngle_degree = float(couch)
        beam.isocenterPosition_mm = list(iso)
        beam.xBeamletSpacing_mm = bx
        beam.yBeamletSpacing_mm = by

        segment = PlanPhotonSegment()
        segment.gantryAngle_degree = float(gantry)
        segment.couchAngle_degree = float(couch)
        segment.isocenterPosition_mm = list(iso)
        segment.xBeamletSpacing_mm = bx
        segment.yBeamletSpacing_mm = by
        segment.x_jaw_mm = [float(jaw_x_mm[0]), float(jaw_x_mm[1])]
        segment.y_jaw_mm = [float(jaw_y_mm[0]), float(jaw_y_mm[1])]
        segment.Xmlc_mm = mlc.copy()
        segment.mu = float(mu_per_beam)
        segment.controlPointIndex = 0
        segment.createBeamletsFromSegments()

        beam.appendBeamSegment(segment)
        plan.appendBeam(beam)

    return plan


def generate_photon_beamlets(
    ct: Any,
    patient: Any,
    machine_model: PhotonMachineModel,
    beam_set: BeamSetSpec,
    params: DeliveryParams,
    monitor_units_per_beam: float = 5000.0,
) -> PhotonBuildResult:
    """Build a photon plan of open fields and summarize its beamlet grid.

    ``ct`` and ``patient`` are kept for symmetry with the proton builder;
    open-field construction does not need them, dose calculation does.
    """
    jaw_x, jaw_y = _resolve_jaw_opening(params, machine_model)
    bx, by = params.beamlet_size_mm or (5.0, 5.0)
    leaf_width = float(params.mlc_leaf_width_mm or machine_model.mlc_leaf_width_mm)
    grid_dims = (
        max(1, math.ceil(jaw_x / bx)),
        max(1, math.ceil(jaw_y / by)),
    )
    elements_per_beam = grid_dims[0] * grid_dims[1]

    logger.info(
        "Building photon plan: %d beams, jaw=%.1f×%.1f mm, leaf=%.1f mm, "
        "beamlet=%.1f×%.1f mm → grid %s (%d elements/beam)",
        len(beam_set.beams), jaw_x, jaw_y, leaf_width, bx, by, grid_dims, elements_per_beam,
    )

    photon_plan = build_photon_plan(
        beams=[(b.gantry_deg, b.couch_deg) for b in beam_set.beams],
        jaw_x_mm=(-jaw_x / 2.0, jaw_x / 2.0),
        jaw_y_mm=(-jaw_y / 2.0, jaw_y / 2.0),
        leaf_width_mm=leaf_width,
        mu_per_beam=monitor_units_per_beam,
        beamlet_spacing_mm=(float(bx), float(by)),
        isocenter_mm=tuple(beam_set.isocenter_mm),
    )

    per_beam: List[PerBeamElements] = []
    for beam_spec, beam in zip(beam_set.beams, photon_plan.beams):
        per_beam.append(
            PerBeamElements(
                beam_id=beam_spec.beam_id,
                element_count=elements_per_beam,
                grid_dims=grid_dims,
                active_beamlets=int(beam.numberOfBeamlets),
            )
        )

    fluence = FluenceElementSet(
        total_count=elements_per_beam * len(beam_set.beams),
        per_beam=per_beam,
    )
    return PhotonBuildResult(fluence_elements=fluence, plan=photon_plan)


